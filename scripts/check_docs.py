#!/usr/bin/env python3
"""Check docs/engineering-principles/ against the conventions in its README.md.

Usage: python3 -I scripts/check_docs.py [file ...]   (default: all docs/engineering-principles/*.md)
       python3 -I scripts/check_docs.py --export [PATH]   (default: rules.yml at the repo root)
Exit code 1 if any error. Warnings do not fail.

--export runs the normal checks, then writes every rule (ID, level, enforcement tag
and tool, owning doc, owner role, text, RETIRED status) to a YAML file, re-parses the
file and fails if the re-parsed count differs from the checker's rule count. It also
prints a summary of machine-enforced (ci/lint/test) vs human-enforced (review/manual)
rules. The output uses JSON-quoted scalars only (valid YAML; stdlib-only, no PyYAML).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs" / "engineering-principles"
PREFIX = {
    "00": "TEC", "01": "PRC", "02": "SEC", "03": "ARC", "04": "PRN", "05": "DEC",
    "06": "SCR", "07": "IGN", "08": "AGT", "09": "STR", "10": "OBS", "11": "CLN",
    "12": "GOV", "13": "DAT", "14": "EVL", "15": "LLM", "16": "CIC", "17": "API",
    "18": "REL", "19": "RAG", "20": "DEP", "21": "WVR", "22": "LOC", "23": "FDY",
    "24": "TST", "25": "REG", "26": "UCS",
}
RULE = re.compile(
    r"^- \*\*([A-Z]{3}-\d{3})\*\* \[(MUST|SHOULD|MAY|RETIRED)\] "
    r"\[(lint|ci|test|review|runtime|manual)(?:: [^\]]+)?\] \S"
)
RULE_START = re.compile(r"^- \*\*([A-Z]{3}-\d{3})\*\*")
# Same shape as RULE, but with capture groups; used only by --export.
RULE_FULL = re.compile(
    r"^- \*\*([A-Z]{3}-\d{3})\*\* \[(MUST|SHOULD|MAY|RETIRED)\] "
    r"\[(lint|ci|test|review|runtime|manual)(?:: ([^\]]+))?\] (\S.*)$"
)
OWNER = re.compile(r"^> \*\*Owner:\*\* (.+?) · \*\*Last verified:\*\*")
ID_ANY = re.compile(r"\b([A-Z]{3}-\d{3})\b")
REQUIRED = ["## Purpose", "## Rules", "## Checklist", "## Common AI failure modes", "## Related docs"]
HEADER = re.compile(
    r"^> \*\*Owner:\*\* .+ · \*\*Last verified:\*\* \d{4}-\d{2}-\d{2} · "
    r"\*\*Status:\*\* (Draft|Reviewed|Adopted)"
)
BANNED = [
    (re.compile(r"\bPRs?\b"), 'use "merge request (MR)", not PR'),
    (re.compile(r"\.github\b"), "GitLab only; no .github paths"),
    (re.compile(r"/Users/|/home/\w+"), "no local paths"),
    (re.compile(r"swapnil", re.I), "no personal names"),
    (re.compile(r"shipping-ai-code-at-scale"), "cite writeup by title only"),
    (re.compile(r"\bBicep\b"), "Terraform is the IaC choice"),
]
# placeholder-ID pattern used in examples, e.g. SEC-014 inside README conventions
LINK = re.compile(r"\]\((\.?/?[^)#\s]+\.md)(#[^)]*)?\)")
SECRET = re.compile(r"(AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----|sk-[A-Za-z0-9]{20,})")


def doc_num(p: Path) -> str | None:
    m = re.match(r"(\d\d)-", p.name)
    return m.group(1) if m else None


def parse_rules(f: Path) -> list[dict[str, object]]:
    """Return every rule line of one doc (fenced blocks skipped, as in the checks)."""
    lines = f.read_text().splitlines()
    owner = next((m.group(1) for l in lines[:6] if (m := OWNER.match(l))), "")
    rules: list[dict[str, object]] = []
    in_fence = False
    for line in lines:
        if line.startswith("```"):
            in_fence = not in_fence
        if in_fence or not RULE_START.match(line):
            continue
        m = RULE_FULL.match(line)
        if not m:
            continue  # malformed lines are reported by the checker, and break the count check
        rid, level, enforcement, tool, text = m.groups()
        retired = level == "RETIRED"
        rules.append({
            "id": rid,
            "level": None if retired else level,
            "enforcement": enforcement,
            "tool": tool,
            "doc": f.name,
            "owner": owner,
            "retired": retired,
            "text": text,
        })
    return rules


def write_rules_yaml(rules: list[dict[str, object]], out: Path) -> None:
    keys = ["id", "level", "enforcement", "tool", "doc", "owner", "retired", "text"]
    lines = ["# Generated by scripts/check_docs.py --export. Do not edit by hand.", "rules:"]
    for r in rules:
        for i, k in enumerate(keys):
            lines.append(("  - " if i == 0 else "    ") + f"{k}: {json.dumps(r[k], ensure_ascii=False)}")
    out.write_text("\n".join(lines) + "\n")


def read_rules_yaml(path: Path) -> list[dict[str, object]]:
    """Re-parse the export with a parser that accepts only what write_rules_yaml emits."""
    rules: list[dict[str, object]] = []
    for line in path.read_text().splitlines():
        if not line or line.startswith("#") or line == "rules:":
            continue
        m = re.match(r"^(  - |    )([a-z]+): (.*)$", line)
        if not m:
            raise ValueError(f"unparseable line: {line[:60]!r}")
        if m.group(1) == "  - ":
            rules.append({})
        rules[-1][m.group(2)] = json.loads(m.group(3))
    return rules


def export(files: list[Path], out: Path, defined_count: int) -> int:
    rules = [r for f in files if doc_num(f) for r in parse_rules(f)]
    write_rules_yaml(rules, out)
    back = read_rules_yaml(out)
    ids = [str(r["id"]) for r in back]
    ok = back == rules and len(set(ids)) == len(ids) == defined_count
    print(f"\nexport: wrote {len(back)} rules to {out}; checker counts {defined_count}: "
          f"{'MATCH' if ok else 'MISMATCH'}")
    live = [r for r in back if not r["retired"]]
    machine = [r for r in live if r["enforcement"] in ("ci", "lint", "test")]
    human = [r for r in live if r["enforcement"] in ("review", "manual")]
    runtime = [r for r in live if r["enforcement"] == "runtime"]
    print(f"summary: {len(live)} active rules, {len(back) - len(live)} retired")
    print(f"  machine-enforced (ci/lint/test): {len(machine)}")
    for tag in ("ci", "lint", "test"):
        print(f"    {tag}: {sum(1 for r in machine if r['enforcement'] == tag)}")
    print(f"  human-enforced (review/manual): {len(human)}")
    for tag in ("review", "manual"):
        print(f"    {tag}: {sum(1 for r in human if r['enforcement'] == tag)}")
    print(f"  runtime: {len(runtime)}")
    return 0 if ok else 1


def main(argv: list[str]) -> int:
    export_to: Path | None = None
    if argv and argv[0] == "--export":
        export_to = Path(argv[1]).resolve() if len(argv) > 1 else ROOT / "rules.yml"
        argv = []

    def in_scope(p: Path) -> bool:
        return p.name == "README.md" or re.match(r"\d\d-", p.name) is not None

    all_files = [p for p in sorted(DOCS.glob("*.md")) if in_scope(p)]
    files = [Path(a).resolve() for a in argv] if argv else all_files
    errors: list[str] = []
    warns: list[str] = []
    defined: dict[str, Path] = {}

    # pass 1: collect IDs from ALL docs so cross-refs resolve even when checking a subset
    for f in all_files:
        num = doc_num(f)
        if not num:
            continue
        in_fence = False
        for line in f.read_text().splitlines():
            if line.startswith("```"):
                in_fence = not in_fence
            if in_fence:
                continue
            m = RULE_START.match(line)
            if m:
                rid = m.group(1)
                if rid in defined and defined[rid] != f:
                    errors.append(f"{f.name}: duplicate ID {rid} (also in {defined[rid].name})")
                defined[rid] = f

    # pass 2: validate
    for f in files:
        if f.name in ("PLAN.md",):
            continue
        text = f.read_text()
        lines = text.splitlines()
        num = doc_num(f)
        rel = f.name

        for pat, why in ([] if f.name == "README.md" else BANNED):
            for i, line in enumerate(lines, 1):
                if pat.search(line):
                    errors.append(f"{rel}:{i}: banned pattern ({why})")
        for i, line in enumerate(lines, 1):
            if SECRET.search(line):
                errors.append(f"{rel}:{i}: possible secret")

        for m in LINK.finditer(text):
            target = (f.parent / m.group(1)).resolve()
            if not target.exists():
                errors.append(f"{rel}: broken link {m.group(1)}")

        if not num:  # README: no rule-format checks
            continue

        if not any(HEADER.match(l) for l in lines[:6]):
            errors.append(f"{rel}: missing/invalid header (Owner · Last verified · Status)")
        pos = -1
        for sec in REQUIRED:
            idx = next((i for i, l in enumerate(lines) if l.strip() == sec), None)
            if idx is None:
                errors.append(f"{rel}: missing section '{sec}'")
            else:
                # order check for the tail sections only
                if sec in REQUIRED[2:]:
                    if idx < pos:
                        errors.append(f"{rel}: section '{sec}' out of order")
                    pos = idx
        expected = PREFIX[num]
        rule_count = 0
        in_fence = False
        for i, line in enumerate(lines, 1):
            if line.startswith("```"):
                in_fence = not in_fence
            if in_fence:
                continue
            start = RULE_START.match(line)
            if start:
                rule_count += 1
                if not RULE.match(line):
                    errors.append(f"{rel}:{i}: malformed rule line")
                rid = start.group(1)
                if not rid.startswith(expected + "-"):
                    errors.append(f"{rel}:{i}: ID {rid} must use prefix {expected}")
        if rule_count == 0:
            errors.append(f"{rel}: no rules found")
        # cross-ref resolution
        for i, line in enumerate(lines, 1):
            if line.startswith("```"):
                continue
            for rid in ID_ANY.findall(line):
                if rid not in defined and rid.split("-")[0] in PREFIX.values():
                    errors.append(f"{rel}:{i}: reference to undefined rule {rid}")
        if "VERIFY:" not in text and "ASSUMPTION:" not in text:
            warns.append(f"{rel}: no VERIFY:/ASSUMPTION: markers (ok only if no external claims)")

    for w in warns:
        print("WARN ", w)
    for e in errors:
        print("ERROR", e)
    print(f"\n{len(files)} files checked, {len(defined)} rules defined, {len(errors)} errors, {len(warns)} warnings")
    if export_to is not None:
        if errors:
            print("export skipped: fix checker errors first")
            return 1
        return export(all_files, export_to, len(defined))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
