#!/usr/bin/env python3
"""Generate .claude/rules/*.md for the service template from rules.yml.

Usage: python3 -I tools/gen_agent_rules.py [--rules PATH] [--spec PATH] [--check]
  --rules  rules.yml written by `scripts/check_docs.py --export` (default rules.yml at the repo root)
  --spec   selection file (default tools/agent_rules.json)
  --check  write nothing; exit 1 if any output file differs from what would be generated

Also writes the GitLab Duo files from the same selection, so Claude Code and Duo cannot drift:
.gitlab/duo/chat-rules.md (always-loaded specs) and .gitlab/duo/mr-review-instructions.yaml (one
group per spec; `paths` become `fileFilters`, no paths means every file). `duo_dir` in the spec
names the output directory. Files listed under `copied` (hand-copied from doc 08, e.g. python-style
and testing) are read back from the rules directory and added to the Duo files; they are not rewritten. Duo reads AGENTS.md itself (except Code Review Flow), so it is not copied.

Implements AGT-010 (one topic, <= 100 lines, quoted `paths` globs) and AGT-011 (the only
frontmatter field is `paths`). A listed rule must exist, must not be retired and must be tagged
review, manual or runtime (rules tagged ci, lint or test already fail the build). Each bullet is
the first sentence of the rule text from rules.yml plus the rule ID; the full text stays in the docs
(AGT-004: do not restate standards). Stdlib only, so it runs with `python3 -I`.
"""

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
ALLOWED_TAGS = {"review", "manual", "runtime"}
MAX_LINES = 100
LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)")
SENTENCE_END = re.compile(r"(?<=[.])\s+(?=[A-Z`])")
# "(`VERIFY:` ...)" and "(`ASSUMPTION:` ...)" asides belong to the doc, not to an agent instruction.
MARKER_ASIDE = re.compile(r"\s*\(`(?:VERIFY|ASSUMPTION):`[^)]*\)")


def read_rules(path: Path) -> dict[str, dict[str, object]]:
    """Parse the JSON-scalar YAML that `check_docs.py --export` writes."""
    rules: dict[str, dict[str, object]] = {}
    cur: dict[str, object] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^(  - |    )([a-z]+): (.*)$", line)
        if not m:
            continue
        if m.group(1) == "  - ":
            cur = {}
        cur[m.group(2)] = json.loads(m.group(3))
        if m.group(2) == "text":
            rules[str(cur["id"])] = cur
    return rules


def first_sentence(text: str) -> str:
    text = MARKER_ASIDE.sub("", LINK.sub(r"\1", text))
    sentence = SENTENCE_END.split(text, maxsplit=1)[0].strip()
    balanced = sentence.count("`") % 2 == 0 and sentence.count("(") == sentence.count(")")
    return sentence if balanced else text


def render(spec: dict[str, Any], rules: dict[str, dict[str, object]]) -> str:
    out: list[str] = []
    paths = spec["paths"]
    if paths:
        out += ["---", "paths:", *(f'  - "{p}"' for p in paths), "---", ""]
    out += [f"# {spec['title']}", ""]
    out += [
        "<!-- Generated by tools/gen_agent_rules.py from rules.yml; do not edit by hand. "
        "Implements AGT-010, AGT-011. Only rules that no CI job or linter enforces. -->",
        "",
    ]
    for rid in spec["rules"]:
        rule = rules.get(rid)
        if rule is None:
            raise SystemExit(f"{spec['name']}: unknown rule {rid}")
        if rule["retired"]:
            raise SystemExit(f"{spec['name']}: {rid} is retired")
        if rule["enforcement"] not in ALLOWED_TAGS:
            raise SystemExit(f"{spec['name']}: {rid} is tagged {rule['enforcement']}, already enforced")
        sentence = first_sentence(str(rule["text"]))
        if "ASSUMPTION:" in sentence or "VERIFY:" in sentence:
            raise SystemExit(f"{spec['name']}: {rid} still carries an ASSUMPTION/VERIFY marker; drop it from the spec")
        out.append(f"- {sentence.rstrip('.')} ({rid}).")
    out += [f"- {note}" for note in spec["notes"]]
    if len(out) > MAX_LINES:
        raise SystemExit(f"{spec['name']}: {len(out)} lines exceeds {MAX_LINES} (AGT-010)")
    return "\n".join(out) + "\n"


def read_copied(path: Path) -> dict[str, Any]:
    """Spec-like dict (title, paths, bullets) parsed from a hand-written rule file."""
    text = path.read_text(encoding="utf-8")
    paths: list[str] = []
    if text.startswith("---\n"):
        _, block, text = text.split("---\n", 2)
        paths = re.findall(r'^\s+- "([^"]+)"$', block, flags=re.MULTILINE)
    title = re.search(r"^# (.+)$", text, flags=re.MULTILINE)
    if title is None or not any(line.startswith("- ") for line in text.splitlines()):
        raise SystemExit(f"{path.name}: needs an H1 title and bullet rules")
    lines = [line for line in text.splitlines() if line.startswith("- ")]
    return {"name": path.stem, "title": title.group(1), "paths": paths, "bullets": lines}


def bullets(spec: dict[str, Any], rules: dict[str, dict[str, object]]) -> list[str]:
    """Rule sentences for a spec; same validation as render()."""
    if "bullets" in spec:
        return list(spec["bullets"])
    out = render(spec, rules).splitlines()
    return [line for line in out if line.startswith("- ")]


def render_chat_rules(specs: list[dict[str, Any]], rules: dict[str, dict[str, object]]) -> str:
    out = [
        "<!-- Generated by tools/gen_agent_rules.py from rules.yml; do not edit by hand. Implements "
        "AGT-004 (no restated standards; AGENTS.md is read by Duo too), AGT-010. Duo Chat and flows "
        "load this file in every conversation. -->",
        "",
        "- Read `AGENTS.md` first: commands, architecture and never-list live there.",
    ]
    for spec in specs:
        if not spec["paths"]:
            out += bullets(spec, rules)
    scoped = ", ".join(f"`{s['name']}.md`" for s in specs if s["paths"])
    out.append(f"- Before editing matching files, read the topic file in `.claude/rules/` ({scoped}).")
    return "\n".join(out) + "\n"


def render_review_instructions(specs: list[dict[str, Any]], rules: dict[str, dict[str, object]]) -> str:
    out = [
        "# Generated by tools/gen_agent_rules.py from rules.yml; do not edit by hand.",
        "# Implements AGT-004, AGT-010. Read by Duo Code Review Flow only; guidance, not enforcement.",
        "# VERIFY: lint with the GitLab review instructions linter (docs.gitlab.com, customize/review_instructions).",
        "instructions:",
    ]
    for spec in specs:
        out.append(f"  - name: {json.dumps(spec['title'].replace(' (always loaded)', ''))}")
        if spec["paths"]:
            out.append("    fileFilters:")
            out += [f"      - {json.dumps(p)}" for p in spec["paths"]]
        out.append("    instructions: |")
        out += [f"      {i}. {b[2:]}" for i, b in enumerate(bullets(spec, rules), start=1)]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rules", type=Path, default=ROOT / "rules.yml")
    parser.add_argument("--spec", type=Path, default=ROOT / "tools" / "agent_rules.json")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rules = read_rules(args.rules)
    spec = json.loads(args.spec.read_text(encoding="utf-8"))
    out_dir = ROOT / spec["output_dir"]
    stale = []
    outputs = [(out_dir / f"{f['name']}.md", render(f, rules)) for f in spec["files"]]
    if "duo_dir" in spec:
        duo_dir = ROOT / spec["duo_dir"]
        duo_specs = [*spec["files"], *(read_copied(out_dir / f"{n}.md") for n in spec.get("copied", []))]
        outputs += [
            (duo_dir / "chat-rules.md", render_chat_rules(duo_specs, rules)),
            (duo_dir / "mr-review-instructions.yaml", render_review_instructions(duo_specs, rules)),
        ]
    for target, text in outputs:
        target.parent.mkdir(parents=True, exist_ok=True)
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(target.name)
        else:
            target.write_text(text, encoding="utf-8")
            print(f"wrote {target.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    if stale:
        print(f"out of date: {', '.join(stale)} (run tools/gen_agent_rules.py)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
