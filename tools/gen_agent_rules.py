#!/usr/bin/env python3
"""Generate .claude/rules/*.md for the service template from rules.yml.

Usage: python3 -I tools/gen_agent_rules.py [--rules PATH] [--spec PATH] [--check]
  --rules  rules.yml written by `scripts/check_docs.py --export` (default tools/rules.yml)
  --spec   selection file (default tools/agent_rules.json)
  --check  write nothing; exit 1 if any output file differs from what would be generated

Implements AGT-010 (one topic, <= 100 lines, quoted `paths` globs) and AGT-011 (the only
frontmatter field is `paths`). A listed rule must exist, must not be retired and must be tagged
review, manual or runtime (rules tagged ci, lint or test already fail the build). Each bullet is
the first sentence of the rule text from rules.yml plus the rule ID; the full text stays in the docs
(AGT-004: do not restate standards). Stdlib only, so it runs with `python3 -I`.
"""

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
ALLOWED_TAGS = {"review", "manual", "runtime"}
MAX_LINES = 100
LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)")
SENTENCE_END = re.compile(r"(?<=[.])\s+(?=[A-Z`])")
# "(`VERIFY:` ...)" and "(`ASSUMPTION:` ...)" asides belong to the doc, not to an agent instruction.
MARKER_ASIDE = re.compile(r"\s*\(`(?:VERIFY|ASSUMPTION):`[^)]*\)")


def read_rules(path: Path) -> dict[str, dict[str, object]]:
    """Parse the JSON-scalar YAML that `check_docs.py --export` writes."""
    rules: dict[str, dict[str, object]] = {}
    cur: dict[str, object] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^(  - |    )([a-z]+): (.*)$", line)
        if not m:
            continue
        if m.group(1) == "  - ":
            cur = {}
        cur[m.group(2)] = json.loads(m.group(3))
        if m.group(2) == "text":
            rules[str(cur["id"])] = cur
    return rules


def first_sentence(text: str) -> str:
    text = MARKER_ASIDE.sub("", LINK.sub(r"\1", text))
    sentence = SENTENCE_END.split(text, maxsplit=1)[0].strip()
    balanced = sentence.count("`") % 2 == 0 and sentence.count("(") == sentence.count(")")
    return sentence if balanced else text


def render(spec: dict[str, Any], rules: dict[str, dict[str, object]]) -> str:
    out: list[str] = []
    paths = spec["paths"]
    if paths:
        out += ["---", "paths:", *(f'  - "{p}"' for p in paths), "---", ""]
    out += [f"# {spec['title']}", ""]
    out += [
        "<!-- Generated by tools/gen_agent_rules.py from rules.yml; do not edit by hand. "
        "Implements AGT-010, AGT-011. Only rules that no CI job or linter enforces. -->",
        "",
    ]
    for rid in spec["rules"]:
        rule = rules.get(rid)
        if rule is None:
            raise SystemExit(f"{spec['name']}: unknown rule {rid}")
        if rule["retired"]:
            raise SystemExit(f"{spec['name']}: {rid} is retired")
        if rule["enforcement"] not in ALLOWED_TAGS:
            raise SystemExit(f"{spec['name']}: {rid} is tagged {rule['enforcement']}, already enforced")
        sentence = first_sentence(str(rule["text"]))
        if "ASSUMPTION:" in sentence or "VERIFY:" in sentence:
            raise SystemExit(f"{spec['name']}: {rid} still carries an ASSUMPTION/VERIFY marker; drop it from the spec")
        out.append(f"- {sentence.rstrip('.')} ({rid}).")
    out += [f"- {note}" for note in spec["notes"]]
    if len(out) > MAX_LINES:
        raise SystemExit(f"{spec['name']}: {len(out)} lines exceeds {MAX_LINES} (AGT-010)")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rules", type=Path, default=ROOT / "tools" / "rules.yml")
    parser.add_argument("--spec", type=Path, default=ROOT / "tools" / "agent_rules.json")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rules = read_rules(args.rules)
    spec = json.loads(args.spec.read_text(encoding="utf-8"))
    out_dir = ROOT / spec["output_dir"]
    stale = []
    for file_spec in spec["files"]:
        target = out_dir / f"{file_spec['name']}.md"
        text = render(file_spec, rules)
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(target.name)
        else:
            target.write_text(text, encoding="utf-8")
            print(f"wrote {target.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    if stale:
        print(f"out of date: {', '.join(stale)} (run tools/gen_agent_rules.py)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
